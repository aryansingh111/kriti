/**
 * The sample resumes for these templates are short, so the layouts are set a little more generously
 * (slightly larger type, more space between sections) to fill a page the way a real resume would.
 */
export const MORE_SPECS: TemplateSpec[] = RAW_SPECS.map((s) => {
  // fresher samples already carry personal details and a declaration, so they are full as they are
  if (s.category === 'Fresher') return s
  return {
    ...s,
    base: Math.round((s.base + 0.5) * 10) / 10,
    padY: (s.padY ?? 1) * 1.06,
    main: { ...s.main, gap: (s.main.gap ?? 12) + 2 },
    aside: s.aside ? { ...s.aside, gap: (s.aside.gap ?? 13) + 2 } : s.aside,
  }
})
